#!/usr/bin/env bash
# Builds supabase/setup.sql = all migrations + seed in one file, so the database can be set up
# by pasting a single file into the Supabase SQL Editor (no terminal needed).
# Run after changing any migration or the seed: npm run db:setup-file
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/supabase/setup.sql"
{
  echo "-- WHATS POPPIN — full database setup (GENERATED by supabase/build-setup.sh, do not edit by hand)."
  echo "-- Paste this whole file into Supabase → SQL Editor → Run, on a NEW, empty project."
  for f in "$ROOT"/supabase/migrations/*.sql "$ROOT"/supabase/seed.sql; do
    echo
    echo "-- ============================================================================"
    echo "-- $(basename "$f")"
    echo "-- ============================================================================"
    cat "$f"
  done
} > "$OUT"
echo "wrote $OUT"
